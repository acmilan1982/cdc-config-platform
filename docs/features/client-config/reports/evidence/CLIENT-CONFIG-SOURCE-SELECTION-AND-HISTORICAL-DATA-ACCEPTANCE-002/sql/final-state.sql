SET ECHO OFF PAGESIZE 500 LINESIZE 400 VERIFY OFF FEEDBACK OFF TRIMSPOOL ON
COL CLIENT_ID FOR A18
COL FG FOR A2
COL IDS FOR A80
COL DESC_LEN FOR 99999

PROMPT ===SYNTHETIC-CLIENT-ROWS===
SELECT CLIENT_ID, FG_ACTIVE FG, DATA_SOURCE_ID IDS, LENGTHB(CLIENT_DESC) DESC_LEN
  FROM CDC_CLIENT_MULTIPLE
 WHERE CLIENT_ID LIKE 'S2AC-%'
 ORDER BY CLIENT_ID;

PROMPT ===COLUMNS-CDC_CLIENT_MULTIPLE===
COL OWNER FOR A10
COL COLUMN_NAME FOR A30
COL DATA_TYPE FOR A20
SELECT OWNER, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE
  FROM ALL_TAB_COLUMNS
 WHERE TABLE_NAME = 'CDC_CLIENT_MULTIPLE'
   AND OWNER = 'CDC'
 ORDER BY COLUMN_ID;

PROMPT ===COLUMNS-CDC_DATA_SOURCE===
SELECT OWNER, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE
  FROM ALL_TAB_COLUMNS
 WHERE TABLE_NAME = 'CDC_DATA_SOURCE'
   AND OWNER = 'CDC'
 ORDER BY COLUMN_ID;

PROMPT ===SOURCE-ROW-COUNTS===
SELECT COUNT(*) AS TOTAL_ROWS FROM CDC_DATA_SOURCE;
SELECT COUNT(*) AS SYNTHETIC_ROWS
  FROM CDC_DATA_SOURCE
 WHERE DATA_SOURCE_ID LIKE 'S2AC%'
    OR DATA_SOURCE_ID IN ('C01', 'C02', 'S2AM', 'S2AM,C02');
SELECT COUNT(*) AS PREEXISTING_ROWS
  FROM CDC_DATA_SOURCE
 WHERE NOT (DATA_SOURCE_ID LIKE 'S2AC%'
    OR DATA_SOURCE_ID IN ('C01', 'C02', 'S2AM', 'S2AM,C02'));
