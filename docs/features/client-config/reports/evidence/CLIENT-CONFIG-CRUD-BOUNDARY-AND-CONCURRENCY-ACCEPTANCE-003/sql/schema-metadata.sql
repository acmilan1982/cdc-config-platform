PROMPT ==== COLUMNS ====
SELECT TABLE_NAME||'|'||COLUMN_ID||'|'||COLUMN_NAME||'|'||DATA_TYPE||'|'||DATA_LENGTH||'|'||CHAR_LENGTH||'|'||NULLABLE||'|'||DATA_DEFAULT
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME IN ('CDC_CLIENT_MULTIPLE','CDC_DATA_SOURCE')
ORDER BY TABLE_NAME, COLUMN_ID;
PROMPT ==== CONSTRAINTS ====
SELECT TABLE_NAME||'|'||CONSTRAINT_NAME||'|'||CONSTRAINT_TYPE||'|'||STATUS||'|'||SEARCH_CONDITION||'|'||R_CONSTRAINT_NAME||'|'||VALIDATED
FROM USER_CONSTRAINTS
WHERE TABLE_NAME IN ('CDC_CLIENT_MULTIPLE','CDC_DATA_SOURCE')
   OR (CONSTRAINT_TYPE='R' AND R_CONSTRAINT_NAME IN (SELECT CONSTRAINT_NAME FROM USER_CONSTRAINTS WHERE TABLE_NAME IN ('CDC_CLIENT_MULTIPLE','CDC_DATA_SOURCE')))
ORDER BY TABLE_NAME, CONSTRAINT_TYPE, CONSTRAINT_NAME;
PROMPT ==== INDEXES ====
SELECT TABLE_NAME||'|'||INDEX_NAME||'|'||UNIQUENESS||'|'||INDEX_TYPE||'|'||STATUS
FROM USER_INDEXES
WHERE TABLE_NAME IN ('CDC_CLIENT_MULTIPLE','CDC_DATA_SOURCE')
ORDER BY TABLE_NAME, INDEX_NAME;
PROMPT ==== INDEX_COLUMNS ====
SELECT TABLE_NAME||'|'||INDEX_NAME||'|'||COLUMN_POSITION||'|'||COLUMN_NAME
FROM USER_IND_COLUMNS
WHERE TABLE_NAME IN ('CDC_CLIENT_MULTIPLE','CDC_DATA_SOURCE')
ORDER BY TABLE_NAME, INDEX_NAME, COLUMN_POSITION;
PROMPT ==== TRIGGERS ====
SELECT TABLE_NAME||'|'||TRIGGER_NAME||'|'||TRIGGER_TYPE||'|'||TRIGGERING_EVENT||'|'||STATUS
FROM USER_TRIGGERS
WHERE TABLE_NAME IN ('CDC_CLIENT_MULTIPLE','CDC_DATA_SOURCE')
ORDER BY TABLE_NAME, TRIGGER_NAME;
PROMPT ==== REFERENCES_TO_TARGETS ====
SELECT c.TABLE_NAME||'|'||c.CONSTRAINT_NAME||'|'||c.CONSTRAINT_TYPE||'|'||rc.TABLE_NAME||'|'||rc.CONSTRAINT_NAME
FROM USER_CONSTRAINTS c JOIN USER_CONSTRAINTS rc ON c.R_CONSTRAINT_NAME = rc.CONSTRAINT_NAME
WHERE c.CONSTRAINT_TYPE='R' AND rc.TABLE_NAME IN ('CDC_CLIENT_MULTIPLE','CDC_DATA_SOURCE')
ORDER BY c.TABLE_NAME, c.CONSTRAINT_NAME;
