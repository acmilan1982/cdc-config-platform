PROMPT ==== COLUMNS ====
SELECT TABLE_NAME||'|'||COLUMN_ID||'|'||COLUMN_NAME||'|'||DATA_TYPE||'|'||DATA_LENGTH||'|'||CHAR_LENGTH||'|'||NULLABLE
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME IN ('CDC_CLIENT_MULTIPLE','CDC_DATA_SOURCE')
ORDER BY TABLE_NAME, COLUMN_ID;
PROMPT ==== CONSTRAINT_NAMES ====
SELECT TABLE_NAME||'|'||CONSTRAINT_NAME||'|'||CONSTRAINT_TYPE||'|'||STATUS||'|'||NVL(R_CONSTRAINT_NAME,'-')||'|'||VALIDATED||'|'||NVL(GENERATED,'-')
FROM USER_CONSTRAINTS
WHERE TABLE_NAME IN ('CDC_CLIENT_MULTIPLE','CDC_DATA_SOURCE')
ORDER BY TABLE_NAME, CONSTRAINT_TYPE, CONSTRAINT_NAME;
PROMPT ==== CHECK_CONDITIONS ====
SET LONG 4000
SELECT TABLE_NAME||'|'||CONSTRAINT_NAME||'|'||SEARCH_CONDITION
FROM USER_CONSTRAINTS
WHERE TABLE_NAME IN ('CDC_CLIENT_MULTIPLE','CDC_DATA_SOURCE') AND CONSTRAINT_TYPE='C'
ORDER BY TABLE_NAME, CONSTRAINT_NAME;
PROMPT ==== FOREIGN_KEY_REFERENCES_TO_TARGETS ====
SELECT c.TABLE_NAME||'|'||c.CONSTRAINT_NAME||'|'||rc.TABLE_NAME||'|'||rc.CONSTRAINT_NAME
FROM USER_CONSTRAINTS c JOIN USER_CONSTRAINTS rc ON c.R_CONSTRAINT_NAME = rc.CONSTRAINT_NAME
WHERE c.CONSTRAINT_TYPE='R' AND rc.TABLE_NAME IN ('CDC_CLIENT_MULTIPLE','CDC_DATA_SOURCE')
ORDER BY c.TABLE_NAME, c.CONSTRAINT_NAME;
